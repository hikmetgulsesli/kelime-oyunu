/**
 * Get a random word from the list
 */
export function getRandomWord(): string {
  return VALID_WORDS[Math.floor(Math.random() * VALID_WORDS.length)];
}

/**
 * Check if a word is in the valid words list
 */
export function isValidWord(word: string): boolean {
  return VALID_WORDS.includes(word.toUpperCase());
}

/**
 * Get the word for a specific day (daily word)
 * Uses a seeded random generator based on the date
 */
export function getDailyWord(date: Date = new Date()): string {
  const start = new Date(2023, 0, 1); // Start date: Jan 1, 2023
  const diff = Math.floor((date.getTime() - start.getTime()) / (1000 * 60 * 60 * 24));
  const index = diff % VALID_WORDS.length;
  return VALID_WORDS[index];
}
